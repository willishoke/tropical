"""Export the mechanically lifted thumbv6m (and LLVM) kernels as Lean BitVec
definitions, sharing preserved with `let`, for checking against a Lean spec
with bv_decide.  Writes lean/Lifted.lean."""
import os, subprocess
import z3, llsym, thumbsym
from tv import OBJDUMP, HERE

def lean_of(e, name, params):
    lets, memo = [], {}
    def go(t):
        k = t.get_id()
        if k in memo: return memo[k]
        if z3.is_bv_value(t):
            s = '(%d#%d)' % (t.as_long(), t.size()); memo[k] = s; return s
        if z3.is_true(t): return 'true'
        if z3.is_false(t): return 'false'
        if z3.is_const(t):
            s = t.decl().name(); memo[k] = s; return s
        d = t.decl().kind(); a = [go(c) for c in t.children()]
        K = z3
        if d == K.Z3_OP_BADD: s = ' + '.join(a)
        elif d == K.Z3_OP_BSUB: s = '%s - %s' % tuple(a)
        elif d == K.Z3_OP_BMUL: s = ' * '.join(a)
        elif d == K.Z3_OP_BAND: s = ' &&& '.join(a)
        elif d == K.Z3_OP_BOR: s = ' ||| '.join(a)
        elif d == K.Z3_OP_BXOR: s = ' ^^^ '.join(a)
        elif d == K.Z3_OP_BASHR: s = 'BitVec.sshiftRight\' %s %s' % tuple(a)
        elif d == K.Z3_OP_BLSHR: s = '%s >>> %s' % tuple(a)
        elif d == K.Z3_OP_BSHL: s = '%s <<< %s' % tuple(a)
        elif d == K.Z3_OP_EXTRACT:
            hi, lo = t.decl().params(); s = 'BitVec.extractLsb\' %d %d %s' % (lo, hi - lo + 1, a[0])
        elif d == K.Z3_OP_CONCAT: s = ' ++ '.join(a)
        elif d == K.Z3_OP_SIGN_EXT: s = 'BitVec.signExtend %d %s' % (t.size(), a[0])
        elif d == K.Z3_OP_ZERO_EXT: s = 'BitVec.zeroExtend %d %s' % (t.size(), a[0])
        elif d == K.Z3_OP_ITE: s = 'if %s then %s else %s' % tuple(a)
        elif d == K.Z3_OP_EQ: s = '%s == %s' % tuple(a)
        elif d == K.Z3_OP_DISTINCT: s = '%s != %s' % tuple(a)
        elif d == K.Z3_OP_NOT: s = '!%s' % a[0]
        elif d == K.Z3_OP_AND: s = ' && '.join(a)
        elif d == K.Z3_OP_OR: s = ' || '.join(a)
        elif d == K.Z3_OP_SLT: s = 'BitVec.slt %s %s' % tuple(a)
        elif d == K.Z3_OP_SGT: s = 'BitVec.slt %s %s' % (a[1], a[0])
        elif d == K.Z3_OP_SLEQ: s = 'BitVec.sle %s %s' % tuple(a)
        elif d == K.Z3_OP_SGEQ: s = 'BitVec.sle %s %s' % (a[1], a[0])
        else: raise Exception('no Lean spelling for %s' % t.decl())
        v = 't%d' % len(lets); lets.append((v, s)); memo[k] = v; return v
    root = go(e)
    sig = ' '.join('(%s : BitVec %d)' % (p.decl().name(), p.size()) for p in params)
    ty = 'BitVec %d' % e.size() if z3.is_bv(e) else 'Bool'
    body = '\n'.join('  let %s := %s' % (v, s) for v, s in lets)
    return 'def %s %s : %s :=\n%s\n  %s\n' % (name, sig, ty, body, root)

if __name__ == '__main__':
    F = z3.BitVec('freq', 32); P = z3.BitVec('phase', 32); T = z3.BitVec('tau', 64)
    dis = subprocess.run([OBJDUMP, '-d', '--triple=thumbv6m-none-eabi',
                          os.path.join(HERE, 'lfo_knob2-m0.o')], capture_output=True, text=True).stdout
    callee = {r: z3.BitVec('orig_' + r, 32) for r in ('r4', 'r5', 'r6', 'r7', 'lr')}
    regs0 = dict(callee, r0=('ptr', 'tau', 0), r1=('ptr', 'in1', 0), r2=('ptr', 'in2', 0), r3=('ptr', 'out', 0))
    loads = {('in1', 0): F, ('in2', 0): P, ('tau', 0): z3.Extract(31, 0, T), ('tau', 4): z3.Extract(63, 32, T)}
    th = thumbsym.merge(thumbsym.run(dis, 'tropical_kernel', regs0, loads), ('out', 0))
    ll = open(os.path.join(HERE, 'lfo_knob2-m0.o.ll')).read()
    lv = llsym.run(ll, {'%tau': {(0, 'i64'): T}, '%in_1': {(0, 'i32'): F},
                        '%in_2': {(0, 'i32'): P}, '%out': 'out'})[0]
    lv = z3.simplify(lv, bv_ite2id=False)  # folds the constant f64 chain for M; see note in REPORT
    os.makedirs(os.path.join(HERE, 'lean'), exist_ok=True)
    with open(os.path.join(HERE, 'lean', 'Lifted.lean'), 'w') as f:
        f.write('-- GENERATED by tolean.py from lfo_knob2-m0.o (llvm-objdump) and lfo_knob2-m0.o.ll\n')
        f.write('set_option maxRecDepth 100000\n\n')
        f.write(lean_of(th, 'thumbKernel', [F, P, T]) + '\n')
        f.write(lean_of(lv, 'llvmKernel', [F, P, T]) + '\n')
    print('wrote lean/Lifted.lean')

def emit_cuts():
    """Cut-point fragments of the thumb object: (a) 0 -> 0x5c: r0 (x) and r1;
    (b) 0x5c -> return with r0 = x, r1 = 1 and every other register free."""
    F = z3.BitVec('freq', 32); P = z3.BitVec('phase', 32); T = z3.BitVec('tau', 64)
    dis = subprocess.run([OBJDUMP, '-d', '--triple=thumbv6m-none-eabi',
                          os.path.join(HERE, 'lfo_knob2-m0.o')], capture_output=True, text=True).stdout
    callee = {r: z3.BitVec('orig_' + r, 32) for r in ('r4', 'r5', 'r6', 'r7', 'lr')}
    regs0 = dict(callee, r0=('ptr', 'tau', 0), r1=('ptr', 'in1', 0), r2=('ptr', 'in2', 0), r3=('ptr', 'out', 0))
    loads = {('in1', 0): F, ('in2', 0): P, ('tau', 0): z3.Extract(31, 0, T), ('tau', 4): z3.Extract(63, 32, T)}
    (a,) = thumbsym.run(dis, 'tropical_kernel', regs0, loads, stop=0x5c)
    X = z3.BitVec('x', 32)
    junk = {r: z3.BitVec('j' + r, 32) for r in ('r2', 'r4', 'r5', 'r6', 'r7')}
    regs = dict(callee, **junk); regs.update(r0=X, r1=z3.BitVecVal(1, 32), r3=('ptr', 'out', 0))
    b = thumbsym.merge(thumbsym.run(dis, 'tropical_kernel', regs, {}, start=0x5c, stack0=callee), ('out', 0))
    with open(os.path.join(HERE, 'lean', 'LiftedCuts.lean'), 'w') as f:
        f.write('-- GENERATED by tolean.py (emit_cuts) from lfo_knob2-m0.o\n\n')
        f.write(lean_of(a[2]['r0'], 'thumbX', [F, P, T]) + '\n')
        for r in ('r1', 'r2', 'r4', 'r5', 'r6', 'r7'):
            v = a[2][r]
            f.write(lean_of(v, 'thumb' + r.upper(), [F, P, T]) + '\n')
        f.write(lean_of(b, 'thumbTail', [X] + [junk[r] for r in sorted(junk)]) + '\n')
    print('wrote lean/LiftedCuts.lean')

if __name__ == '__main__' and os.environ.get('CUTS'):
    emit_cuts()
